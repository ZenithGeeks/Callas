"""Print the LangGraph pipelines as Mermaid diagrams, straight from the compiled graphs.

    python -m orchestrator.show_graph            # print to the terminal
    python -m orchestrator.show_graph --out docs/diagrams/langgraph.md

Rendering happens locally from the graph structure; no model, server or call data is used.
GitHub and most Markdown viewers draw the ```mermaid blocks in the output file.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from llm_serving.fake import FakeLLM
from orchestrator.graph import Runtime, build_message_graph, build_turn_graph


class _SilentSpeaker:
    """Stand-in so the optional speak node is part of the drawn turn graph."""

    def synthesize_bytes(self, text: str) -> bytes:
        """Return no audio."""
        return b""


def mermaid() -> str:
    """Markdown text with the turn graph (speaker present) and the message graph as Mermaid."""
    rt = Runtime(llm=FakeLLM(), speaker=_SilentSpeaker())
    turn = build_turn_graph(rt).get_graph().draw_mermaid()
    message = build_message_graph(rt).get_graph().draw_mermaid()
    return (
        "# Callas LangGraph pipelines\n\n"
        "Generated by `python -m orchestrator.show_graph --out docs/diagrams/langgraph.md`.\n"
        "Code: `modules/orchestrator/graph.py`. The branch after `decide` is "
        "`route_after_decide`, which reads only `Decision.auto_reply`.\n\n"
        "## Turn graph (one call turn)\n\n"
        f"```mermaid\n{turn.strip()}\n```\n\n"
        "## Message graph (one text message)\n\n"
        f"```mermaid\n{message.strip()}\n```\n"
    )


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", help="write Markdown with Mermaid blocks to this file")
    args = ap.parse_args(argv)
    text = mermaid()
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
